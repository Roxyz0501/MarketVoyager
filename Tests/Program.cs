using MarketVoyager;
int checks = 0;
void Check(bool result, string name) { checks++; if (!result) throw new Exception(name); }
var r = new BuyRule { ItemId = 10, UnitLimit = 100, QuantityLimit = 10, Purchased = 3, Quality = Quality.Nq };
var nq = new Offer(1, 10, 100, 7, 35, false);
Check(Rules.Eligible(r, nq, true), "inclusive price and exact remaining quantity");
Check(!Rules.Eligible(r, nq with { Price = 101 }, true), "price cap");
Check(!Rules.Eligible(r, nq with { Quantity = 8 }, true), "whole stack overrun");
Check(!Rules.Eligible(r, nq with { Quantity = 0 }, true), "zero quantity");
Check(!Rules.Eligible(r, nq with { Item = 11 }, true), "wrong item");
Check(!Rules.Eligible(r, nq with { Hq = true }, true), "NQ rejects HQ");
r.Quality = Quality.Hq;
Check(!Rules.Eligible(r, nq, true), "HQ rejects NQ");
Check(Rules.Eligible(r, nq with { Hq = true }, true), "HQ accepts HQ");
Check(Rules.Eligible(r, nq, false), "no-HQ item falls back to NQ");
Check(!Rules.Eligible(r, nq with { Hq = true }, false), "impossible HQ rejected");
r.Quality = Quality.Any;
Check(Rules.Eligible(r, nq, true) && Rules.Eligible(r, nq with { Hq = true }, true), "Any accepts both");
r.Purchased = 8;
Check(Rules.Eligible(r, nq with { Hq = true, Quantity = 2 }, true), "mixed-quality shared remaining count");
r.Purchased = 10;
Check(!Rules.Eligible(r, nq with { Quantity = 1 }, true), "cap reached");
Check(Rules.Overlaps(r, new() { ItemId = 10, Quality = Quality.Hq }, true), "Any overlaps HQ");
Check(!Rules.Overlaps(new() { ItemId = 10, Quality = Quality.Nq }, new() { ItemId = 10, Quality = Quality.Hq }, true), "separate quality limits");
Check(Rules.Reconcile(10, 13, 3) == Rules.InventoryResult.Purchased, "lost response reconciled");
Check(Rules.Reconcile(10, 10, 3) == Rules.InventoryResult.Unchanged, "retry inventory condition");
Check(Rules.Reconcile(10, 12, 3) == Rules.InventoryResult.Inconsistent, "partial quantity cannot confirm");
Check(Rules.Reconcile(10, 9, 3) == Rules.InventoryResult.Inconsistent, "concurrent removal");
Check(Rules.Reconcile(10, 14, 3) == Rules.InventoryResult.Inconsistent, "extra acquisition");
Check(Rules.Reconcile(-1, 2, 3) == Rules.InventoryResult.Inconsistent, "invalid inventory");
Check(nq.Total == 735, "tax included in gil requirement");
Check(Rules.Normalize("zh_Hant") == "zh-Hant", "traditional normalization");
Check(Rules.Normalize("ja-JP") == "ja", "Japanese region");
Check(Rules.Normalize("zh") == null && Rules.Normalize("auto") == null, "ambiguous and Auto rejected");
Texts.Validate();
foreach (var code in Texts.Codes) Check(Texts.Get("Any", code) != "Any", "Any translation " + code);
var random = new Random(17);
for (int i = 0; i < 10000; i++)
{
    var rule = new BuyRule { ItemId = 10, UnitLimit = random.Next(1, 10000), QuantityLimit = random.Next(1, 1000), Purchased = random.Next(0, 1000), Quality = Quality.Any };
    var offer = new Offer(1, 10, (uint)random.Next(1, 10000), (uint)random.Next(1, 1000), 0, random.Next(2) == 1);
    if (Rules.Eligible(rule, offer, true)) Check((long)rule.Purchased + offer.Quantity <= rule.QuantityLimit && offer.Price <= rule.UnitLimit, "random cap invariant");
}
Console.WriteLine($"Passed {checks} assertions, including 10,000 generated purchase candidates and seven-language completeness.");
Check(Rules.ResolveLanguage("ko", "ja", "en") == "ko", "saved language persists");
Check(Rules.ResolveLanguage(null, "ja", "en") == "ja", "game language first");
Check(Rules.ResolveLanguage("auto", "zh", "fr-FR") == "fr", "unsupported game falls through");
Check(Rules.ResolveLanguage(null, null, "unknown") == "en", "English last fallback");
Check(Texts.Get("Any", "unknown") == Texts.Get("Any", "en"), "English text fallback");
var mixed = new BuyRule { ItemId = 10, UnitLimit = 100, QuantityLimit = 5, Quality = Quality.Any };
Check(Rules.Eligible(mixed, nq with { Quantity = 3 }, true), "mixed first NQ stack");
mixed.Purchased += 3;
Check(Rules.Eligible(mixed, nq with { Hq = true, Quantity = 2 }, true), "mixed final HQ stack");
mixed.Purchased += 2;
Check(!Rules.Eligible(mixed, nq with { Hq = true, Quantity = 1 }, true), "mixed combined cap");
var roundtrip = System.Text.Json.JsonSerializer.Deserialize<BuyRule>(System.Text.Json.JsonSerializer.Serialize(mixed))!;
Check(roundtrip.Purchased == 5 && roundtrip.Quality == Quality.Any, "restart retains Any and bought count");
Console.WriteLine($"Final total: {checks} assertions passed.");

var taxed = new BuyRule { ItemId = 10, UnitLimit = 100, QuantityLimit = 20, IncludeTax = true };
Check(Rules.Eligible(taxed, new(1,10,95,2,10,false),true), "tax-inclusive exact cap");
Check(!Rules.Eligible(taxed, new(1,10,96,2,10,false),true), "tax pushes price over cap");
Check(Rules.NpcLimit(100,5)==95 && Rules.NpcLimit(5,5)==null && Rules.NpcLimit(100,0)==null, "NPC margin boundaries");
var catalogue = new CatalogItem[]{new(10,"Copper",1,"Metal",100,5,true),new(11,"Iron",1,"Metal",200,10,true),new(12,"Apple",2,"Food",5,1,false)};
Check(Catalog.Filter(catalogue,"",1,150,CatalogSort.NpcDescending).Select(x=>x.Id).SequenceEqual(new uint[]{11}),"combined category and minimum price");
Check(Catalog.Filter(catalogue,"cop",0,0,CatalogSort.Name).Single().Id==10,"case-insensitive name");
Check(Catalog.Filter(catalogue,"12",0,0,CatalogSort.Id).Single().Id==12,"ID search");
Check(Catalog.Filter(catalogue,"",0,0,CatalogSort.NpcDescending).Select(x=>x.Id).SequenceEqual(new uint[]{11,10,12}),"NPC descending sort");
var list = new ShoppingList(); var options=new BatchOptions(100,10,Quality.Any,false,true,5);
var added=Catalog.Add(list,catalogue,options);
Check(added.Changed==2 && added.Skipped==1 && list.Items.All(x=>x.IncludeTax),"bulk NPC mode skips unprofitable item");
Check(Catalog.Add(list,catalogue,options).Changed==0,"repeat additions deduplicated");
var ledger = list.Items[0]; Sales.Credit(ledger,7,false,5); Sales.Credit(ledger,7,true,2);
Check(ledger.Purchased==7 && ledger.Stock.Sum(x=>x.Remaining)==7,"confirmed purchase credits independent stock ledger");
var edits=Catalog.Edit(list,new HashSet<Guid>{ledger.Id},catalogue.ToDictionary(x=>x.Id),options with {Price=50,NpcMode=false,SetQuality=false});
Check(edits.Changed==1 && ledger.Purchased==7 && ledger.Stock.Sum(x=>x.Remaining)==7,"bulk edit preserves both counters");
var sale=new SaleReservation{RuleId=ledger.Id,Item=ledger.ItemId,Character=7,Hq=false,Quantity=5,Before=15,GilBefore=100,ExpectedGil=500};
Check(Sales.ShouldVisit(true,0,0) && Sales.ShouldVisit(true,5,5) && !Sales.ShouldVisit(false,0,5) && !Sales.ShouldVisit(true,6,5),"full inventory and configured threshold");
Check(Sales.Reconcile(sale,15,100)==Sales.Outcome.Waiting,"sale pending blocks repeat");
Check(Sales.Reconcile(sale,10,100)==Sales.Outcome.Waiting,"inventory receipt precedes wallet");
Check(Sales.Reconcile(sale,15,600)==Sales.Outcome.Waiting,"wallet precedes inventory");
Check(Sales.Reconcile(sale,10,600)==Sales.Outcome.Sold,"sale confirmed by quantity and gil");
Check(Sales.Reconcile(sale,9,600)==Sales.Outcome.Inconsistent && Sales.Reconcile(sale,10,700)==Sales.Outcome.Inconsistent,"wrong sale amount or gil stops");
Sales.Complete(ledger,sale);
Check(ledger.Purchased==7 && ledger.Stock.Single().Hq && ledger.Stock.Single().Remaining==2,"sale does not decrease purchased count or other quality");
Check(Rules.Eligible(ledger,new(7,10,50,3,0,false),true),"resumed buying retains remaining cap after sale");
Sales.Credit(ledger,7,false,3);
Check(!Rules.Eligible(ledger,new(8,10,50,1,0,false),true),"resumed shopping stops at original cap");
var saved = System.Text.Json.JsonSerializer.Deserialize<ShoppingList>(System.Text.Json.JsonSerializer.Serialize(list))!;
Check(saved.Items[0].Purchased==10 && saved.Items[0].Stock.Sum(x=>x.Remaining)==5,"restart preserves sale and purchase accounts");
Check(Catalog.Reset(list,new HashSet<Guid>{ledger.Id})==1 && ledger.Purchased==0 && ledger.Stock.Sum(x=>x.Remaining)==5,"selective reset leaves unsold stock intact");
var separate=new ShoppingList{Items=[new(){ItemId=10,Quality=Quality.Nq},new(){ItemId=10,Quality=Quality.Hq}]};
var conflict=Catalog.Edit(separate,separate.Items.Select(x=>x.Id).ToHashSet(),catalogue.ToDictionary(x=>x.Id),options);
Check(conflict.Error=="Overlap" && separate.Items[0].Quality==Quality.Nq && separate.Items[1].Quality==Quality.Hq,"conflicting batch edit is atomic");
var huge=Enumerable.Range(1,1001).Select(x=>new CatalogItem((uint)x,"Item",1,"Category",100,1,false)).ToArray();
var empty=new ShoppingList();
Check(Catalog.Add(empty,huge,options).Error=="Capacity" && empty.Items.Count==0,"oversize results add no partial batch");
Check(Catalog.Add(empty,huge.Take(1000),options).Changed==1000 && empty.Items.All(x=>x.Quality==Quality.Nq),"1000 row boundary and no HQ normalization");
try { Sales.Complete(ledger,sale); Check(false,"duplicate sale accepted"); } catch(InvalidOperationException) { Check(true,"duplicate sale blocked"); }
Console.WriteLine($"Complete suite: {checks} assertions passed.");
